def increase(value, addValue):
    newValue = value + (addValue * value / 100)
    return newValue

def decrease(value, minusValue):
    newValue = value - (minusValue * value / 100)
    return newValue

def half(value):
    newValue = value / 2
    return newValue

def double(value):
    newValue = value * 2
    return newValue